% Generate_Figures_Rev18.m
% All figures black/white/grayscale only - datasets distinguished by marker
% shape and line style, not color, per IEEE black-and-white formatting requirement.
%
% Sensorless Load Estimation via Motor Current on a Low-Cost VFD-Driven Induction Motor
% Single, fully standalone script - no external data file needed (see the embedded
% DATA table below; this fixed repeated "no groups.csv found" failures when the
% script was shared on its own, away from the rest of the repo).
%
% Run this single file directly, from anywhere:
%   octave Generate_Figures_Rev18.m
% or in MATLAB:
%   Generate_Figures_Rev18
%
% Writes: a "figures" subfolder next to wherever this script itself is saved.
%
% STANDING RULE: every output filename below is prefixed with its real, current
% paper figure number (figNN_description.png) and every section comment below
% must say the same number. If a paper revision ever renumbers a figure, update
% the filename AND this table in the same pass - never let them drift apart.
%
% Output -> paper figure map (current as of Rev 16):
%   fig01_block_diagram.png        Fig. 1  (schematic, no data - drawn, not plotted)
%   (not produced here)            Fig. 2  (full test rig photo - see
%                                            paper_rev0/assets/12.jpg)
%   (not produced here)            Fig. 3  (Drum_Rev_0 CAD render - see
%                                            paper_rev0/assets/drum_cad_cropped.png)
%   (not produced here)            Fig. 4  (VFD wired photo - see
%                                            paper_rev0/assets/vfd_wired.jpg)
%   fig05_rs485_wiring.png         Fig. 5  (schematic, no data - drawn, not plotted)
%   (not produced here)            Fig. 6  (raw USART2 screenshot - see
%                                            paper_rev0/assets/raw_csv_screenshot.png)
%   (not produced here)            Fig. 7  (STM32 firmware control-flow chart - David's
%                                            explicit Rev 11 chat request; see
%                                            paper_rev0/assets/fig_sw_flowchart.png,
%                                            generated by scratchpad/flowchart/
%                                            gen_flowchart.m, not by this script)
%   fig08_baseline_slip.png        Fig. 8  (no-load baseline, slip panel - up direction
%                                            only, Rev 10 dropped down-direction data
%                                            entirely; see note below)
%   fig09_baseline_current.png     Fig. 9  (same baseline session, current panel)
%   fig10_calibration_fit.png      Fig. 10 (calibrated model, current vs. load)
%   fig11_blind_validation.png     Fig. 11 (blind validation, predicted vs. actual)
%   fig12_torque_validation_slip.png   Fig. 12 (independent SERVO cross-check, slip panel)
%   fig13_torque_validation_torque.png Fig. 13 (same cross-check, torque panel)
%   fig14_loocv_model_comparison.png   Fig. 14 (LOOCV error by model form)
%
% Fig. 1/5 are drawn schematics (wiring per docs/wiring.md + Table III). Fig. 8/9/10 are
% computed directly from the real groups.csv files checked into the repo (genuine
% recomputation, not hardcoded). Fig. 11 reproduces the already-reported blind-
% validation results (Table XI of the paper) - those specific held-out sessions were
% analyzed ad hoc and are not re-derivable from a groups.csv in this repo, so its
% numbers are transcribed here from the paper with a comment, not recomputed. Fig. 14
% IS reproducible: its numbers come directly from tools/model/cross_validate.py, a
% real committed LOOCV script, and are only transcribed into this plotting code
% rather than recomputed in Octave to avoid porting that fitting/CV logic twice.
%
% Rev 10: down-direction (lowering) slip/current data removed from the baseline figure
% entirely - the motor has no dynamic braking, so down-direction readings were never
% physically meaningful and were never used in the paper's model (David's call, Rev 9
% review).
% Rev 11: the torque-validation figure split from one combined two-panel figure into
% two single-panel figures (David's Rev 9 review comment, caught during the full
% comment-resolution audit that produced Rev 11).
% Rev 12: the no-load baseline figure split the same way (Rev 11 review comment 71,
% missed in the Rev 11 pass); real IEEE-template margins/column width applied
% throughout the paper, so every figure here is now sized to fit a single column.

clear; clc; close all;

